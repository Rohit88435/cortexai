import PDFDocument from "pdfkit";

export const generatePdf = async (data = {}) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 0,
      bufferPages: true,

      info: {
        Author: data.author || "CortexAI",
        Title: data.title || "CortexAI Report",
        Subject: data.subtitle || "Generated by CortexAI",
        Creator: "CortexAI",
        Producer: "CortexAI PDF Generator",
        Keywords: "CortexAI, AI, Report",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));

    doc.on("end", () => {
      try {
        addPageNumbers(doc);
        resolve(Buffer.concat(chunks));
      } catch (error) {
        reject(error);
      }
    });

    doc.on("error", reject);

    // ============================================================
    // CONFIG
    // ============================================================

    const PAGE = {
      width: 595.28,
      height: 841.89,

      marginLeft: 55,
      marginRight: 55,

      contentWidth: 485,

      top: 70,
      bottom: 65,
    };

    const COLORS = {
      primary: "#4F46E5",
      primaryDark: "#3730A3",
      primaryLight: "#EEF2FF",

      text: "#111827",
      body: "#374151",
      muted: "#6B7280",
      light: "#9CA3AF",

      border: "#E5E7EB",
      borderDark: "#D1D5DB",

      background: "#F8FAFC",
      white: "#FFFFFF",

      success: "#059669",
      successLight: "#ECFDF5",

      warning: "#D97706",
      warningLight: "#FFFBEB",

      danger: "#DC2626",
      dangerLight: "#FEF2F2",
    };

    const FONT = {
      regular: "Helvetica",
      medium: "Helvetica-Bold",
      bold: "Helvetica-Bold",
      italic: "Helvetica-Oblique",
    };

    // ============================================================
    // DATA NORMALIZATION
    // ============================================================

    const title = cleanText(data.title || "CortexAI Report");

    const subtitle = cleanText(data.subtitle || "");

    const description = cleanText(
      data.description || data.summary || data.overview || "",
    );

    const sections = Array.isArray(data.sections)
      ? data.sections
      : Array.isArray(data.section)
        ? data.section
        : [];

    const generatedDate = data.date ? new Date(data.date) : new Date();

    // ============================================================
    // HELPERS
    // ============================================================

    function cleanText(value) {
      if (value === null || value === undefined) return "";

      return String(value)
        .replace(/\u0000/g, "")
        .replace(/\u0011/g, "-")
        .replace(/\u0010/g, "-")
        .replace(/\r\n/g, "\n")
        .trim();
    }

    function safeNumber(value, fallback = 0) {
      const number = Number(value);

      return Number.isFinite(number) ? number : fallback;
    }

    function formatDate(date) {
      try {
        return new Intl.DateTimeFormat("en-US", {
          year: "numeric",
          month: "long",
          day: "numeric",
        }).format(date);
      } catch {
        return "";
      }
    }

    function formatShortDate(date) {
      try {
        return new Intl.DateTimeFormat("en-US", {
          year: "numeric",
          month: "short",
          day: "numeric",
        }).format(date);
      } catch {
        return "";
      }
    }

    function setFont(font = FONT.regular, size = 11, color = COLORS.body) {
      doc.font(font).fontSize(size).fillColor(color);
    }

    function roundedRect(x, y, width, height, radius, fill) {
      doc.roundedRect(x, y, width, height, radius).fillColor(fill).fill();
    }

    function strokeRoundedRect(
      x,
      y,
      width,
      height,
      radius,
      color,
      lineWidth = 1,
    ) {
      doc
        .roundedRect(x, y, width, height, radius)
        .lineWidth(lineWidth)
        .strokeColor(color)
        .stroke();
    }

    function line(x1, y1, x2, y2, color = COLORS.border, width = 1) {
      doc
        .strokeColor(color)
        .lineWidth(width)
        .moveTo(x1, y1)
        .lineTo(x2, y2)
        .stroke();
    }

    function ensureSpace(requiredHeight = 100) {
      if (doc.y + requiredHeight > PAGE.height - PAGE.bottom) {
        doc.addPage();
        drawPageHeader();
        return true;
      }

      return false;
    }

    function drawPageHeader() {
      const y = 28;

      setFont(FONT.bold, 8, COLORS.primary);

      doc.text("CORTEXAI", PAGE.marginLeft, y, {
        width: 100,
        lineBreak: false,
      });

      setFont(FONT.regular, 8, COLORS.light);

      doc.text("AI-GENERATED REPORT", PAGE.width - PAGE.marginRight - 130, y, {
        width: 130,
        align: "right",
        lineBreak: false,
      });

      line(
        PAGE.marginLeft,
        47,
        PAGE.width - PAGE.marginRight,
        47,
        COLORS.border,
        0.7,
      );
    }

    function drawFooter(pageNumber) {
      const y = PAGE.height - 38;

      line(
        PAGE.marginLeft,
        y - 8,
        PAGE.width - PAGE.marginRight,
        y - 8,
        COLORS.border,
        0.7,
      );

      setFont(FONT.regular, 8, COLORS.light);

      doc.text(data.footerText || "Generated by CortexAI", PAGE.marginLeft, y, {
        width: 180,
        lineBreak: false,
      });

      doc.text(formatShortDate(generatedDate), 205, y, {
        width: 150,
        align: "center",
        lineBreak: false,
      });

      doc.text(`Page ${pageNumber}`, PAGE.width - PAGE.marginRight - 80, y, {
        width: 80,
        align: "right",
        lineBreak: false,
      });
    }

    function drawPageNumbers() {
      const range = doc.bufferedPageRange();

      for (let i = range.start; i < range.start + range.count; i++) {
        doc.switchToPage(i);

        drawFooter(i + 1);
      }
    }

    function addPageNumbers(docInstance) {
      drawPageNumbers();
    }

    function drawBrandBadge() {
      roundedRect(PAGE.marginLeft, 55, 92, 27, 13, COLORS.primary);

      setFont(FONT.bold, 9, COLORS.white);

      doc.text("CORTEXAI", PAGE.marginLeft, 64, {
        width: 92,
        align: "center",
        lineBreak: false,
      });
    }

    function drawDate() {
      setFont(FONT.regular, 9, COLORS.muted);

      doc.text(
        formatDate(generatedDate),
        PAGE.width - PAGE.marginRight - 160,
        64,
        {
          width: 160,
          align: "right",
          lineBreak: false,
        },
      );
    }

    function drawCover() {
      // Background
      doc.rect(0, 0, PAGE.width, PAGE.height).fillColor(COLORS.white).fill();

      // Decorative accent
      doc.rect(0, 0, 8, PAGE.height).fillColor(COLORS.primary).fill();

      // Top brand
      drawBrandBadge();
      drawDate();

      // Small label
      setFont(FONT.bold, 9, COLORS.primary);

      doc.text(
        data.type ? cleanText(data.type).toUpperCase() : "PROFESSIONAL REPORT",
        PAGE.marginLeft,
        150,
        {
          width: PAGE.contentWidth,
          lineBreak: false,
        },
      );

      // Title
      setFont(FONT.bold, 32, COLORS.text);

      doc.text(title, PAGE.marginLeft, 178, {
        width: PAGE.contentWidth,
        lineGap: 4,
        align: "left",
      });

      // Accent line
      line(
        PAGE.marginLeft,
        doc.y + 18,
        PAGE.marginLeft + 65,
        doc.y + 18,
        COLORS.primary,
        4,
      );

      doc.y += 36;

      // Subtitle
      if (subtitle) {
        setFont(FONT.regular, 13, COLORS.muted);

        doc.text(subtitle, PAGE.marginLeft, doc.y, {
          width: PAGE.contentWidth,
          lineGap: 4,
        });

        doc.y += 18;
      }

      // Description card
      if (description) {
        doc.y += 30;

        const cardY = doc.y;

        roundedRect(
          PAGE.marginLeft,
          cardY,
          PAGE.contentWidth,
          105,
          10,
          COLORS.background,
        );

        // Left accent
        doc
          .rect(PAGE.marginLeft, cardY, 4, 105)
          .fillColor(COLORS.primary)
          .fill();

        setFont(FONT.bold, 9, COLORS.primary);

        doc.text("OVERVIEW", PAGE.marginLeft + 20, cardY + 18, {
          width: PAGE.contentWidth - 40,
          lineBreak: false,
        });

        setFont(FONT.regular, 10.5, COLORS.body);

        doc.text(description, PAGE.marginLeft + 20, cardY + 38, {
          width: PAGE.contentWidth - 40,
          lineGap: 4,
        });

        doc.y = cardY + 125;
      }

      // Document stats
      const statsY = Math.min(doc.y + 30, 600);

      drawStat(PAGE.marginLeft, statsY, "SECTIONS", sections.length);

      drawStat(
        PAGE.marginLeft + 165,
        statsY,
        "CREATED",
        formatShortDate(generatedDate),
      );

      drawStat(PAGE.marginLeft + 330, statsY, "SOURCE", "CortexAI");

      // Bottom message
      setFont(FONT.regular, 9, COLORS.light);

      doc.text(
        data.coverNote ||
          "This report was generated automatically using CortexAI.",
        PAGE.marginLeft,
        PAGE.height - 100,
        {
          width: PAGE.contentWidth,
          align: "center",
        },
      );
    }

    function drawStat(x, y, label, value) {
      roundedRect(x, y, 145, 62, 8, COLORS.white);

      strokeRoundedRect(x, y, 145, 62, 8, COLORS.border);

      setFont(FONT.bold, 8, COLORS.light);

      doc.text(label, x + 12, y + 12, {
        width: 121,
        lineBreak: false,
      });

      setFont(FONT.bold, 12, COLORS.text);

      doc.text(String(value), x + 12, y + 30, {
        width: 121,
        lineBreak: false,
      });
    }

    function drawSectionHeading(index, heading) {
      ensureSpace(90);

      const number = String(index + 1).padStart(2, "0");

      setFont(FONT.bold, 9, COLORS.primary);

      doc.text(number, PAGE.marginLeft, doc.y, {
        width: 30,
        lineBreak: false,
      });

      const headingX = PAGE.marginLeft + 38;

      setFont(FONT.bold, 17, COLORS.text);

      doc.text(cleanText(heading || "Untitled Section"), headingX, doc.y, {
        width: PAGE.contentWidth - 38,
        lineGap: 3,
      });

      doc.moveDown(0.5);

      line(
        PAGE.marginLeft,
        doc.y,
        PAGE.width - PAGE.marginRight,
        doc.y,
        COLORS.border,
        1,
      );

      doc.y += 15;
    }

    function drawBullet(point) {
      const text = cleanText(point);

      if (!text) return;

      // Keep bullet and text together
      ensureSpace(40);

      const startY = doc.y;

      // Bullet
      doc
        .circle(PAGE.marginLeft + 7, startY + 6, 3)
        .fillColor(COLORS.primary)
        .fill();

      setFont(FONT.regular, 10.5, COLORS.body);

      doc.text(text, PAGE.marginLeft + 22, startY, {
        width: PAGE.contentWidth - 22,
        lineGap: 4,
        paragraphGap: 7,
      });

      doc.y += 4;
    }

    function drawHighlight(highlight) {
      if (!highlight) return;

      ensureSpace(85);

      const y = doc.y;

      const type = highlight.type || "info";

      let background = COLORS.primaryLight;
      let accent = COLORS.primary;

      if (type === "success") {
        background = COLORS.successLight;
        accent = COLORS.success;
      }

      if (type === "warning") {
        background = COLORS.warningLight;
        accent = COLORS.warning;
      }

      if (type === "danger") {
        background = COLORS.dangerLight;
        accent = COLORS.danger;
      }

      const label = cleanText(highlight.label || "IMPORTANT");

      const text = cleanText(highlight.text || highlight.message || "");

      roundedRect(PAGE.marginLeft, y, PAGE.contentWidth, 78, 9, background);

      doc.rect(PAGE.marginLeft, y, 4, 78).fillColor(accent).fill();

      setFont(FONT.bold, 8, accent);

      doc.text(label.toUpperCase(), PAGE.marginLeft + 18, y + 13, {
        width: PAGE.contentWidth - 36,
        lineBreak: false,
      });

      setFont(FONT.regular, 10, COLORS.body);

      doc.text(text, PAGE.marginLeft + 18, y + 30, {
        width: PAGE.contentWidth - 36,
        lineGap: 3,
      });

      doc.y = y + 95;
    }

    function drawKeyValueTable(items = []) {
      if (!Array.isArray(items) || items.length === 0) {
        return;
      }

      ensureSpace(100);

      const x = PAGE.marginLeft;
      const width = PAGE.contentWidth;

      const keyWidth = 155;
      const valueWidth = width - keyWidth;

      items.forEach((item, index) => {
        const key = cleanText(item.key || "");
        const value = cleanText(item.value || "");

        setFont(FONT.bold, 9.5, COLORS.text);

        const keyHeight = doc.heightOfString(key, {
          width: keyWidth - 24,
          lineGap: 3,
        });

        setFont(FONT.regular, 9.5, COLORS.body);

        const valueHeight = doc.heightOfString(value, {
          width: valueWidth - 24,
          lineGap: 3,
        });

        const rowHeight = Math.max(keyHeight, valueHeight) + 22;

        if (doc.y + rowHeight > PAGE.height - PAGE.bottom) {
          doc.addPage();
          drawPageHeader();
        }

        const y = doc.y;

        if (index % 2 === 0) {
          roundedRect(x, y, width, rowHeight, 4, COLORS.background);
        }

        setFont(FONT.bold, 9.5, COLORS.text);

        doc.text(key, x + 12, y + 11, {
          width: keyWidth - 24,
          lineGap: 3,
        });

        setFont(FONT.regular, 9.5, COLORS.body);

        doc.text(value, x + keyWidth + 12, y + 11, {
          width: valueWidth - 24,
          lineGap: 3,
        });

        doc.y = y + rowHeight;
      });

      doc.y += 15;
    }

    function drawSection(section, index) {
      drawSectionHeading(index, section.heading || section.title);

      // Section description
      if (section.description) {
        setFont(FONT.regular, 10.5, COLORS.body);

        doc.text(cleanText(section.description), PAGE.marginLeft, doc.y, {
          width: PAGE.contentWidth,
          lineGap: 4,
        });

        doc.moveDown(0.8);
      }

      // Optional key/value table
      if (Array.isArray(section.table)) {
        drawKeyValueTable(section.table);
      }

      // Optional highlight
      if (section.highlight) {
        drawHighlight(section.highlight);
      }

      // Standard points
      const points = Array.isArray(section.points) ? section.points : [];

      points.forEach((point) => {
        drawBullet(point);
      });

      // Optional nested subsections
      if (Array.isArray(section.subsections)) {
        section.subsections.forEach((subsection) => {
          ensureSpace(80);

          setFont(FONT.bold, 12, COLORS.text);

          doc.text(
            cleanText(subsection.heading || subsection.title),
            PAGE.marginLeft,
            doc.y,
          );

          doc.moveDown(0.4);

          if (subsection.description) {
            setFont(FONT.regular, 10, COLORS.body);

            doc.text(
              cleanText(subsection.description),
              PAGE.marginLeft,
              doc.y,
              {
                width: PAGE.contentWidth,
                lineGap: 3,
              },
            );

            doc.moveDown(0.5);
          }

          if (Array.isArray(subsection.points)) {
            subsection.points.forEach(drawBullet);
          }

          doc.moveDown(0.5);
        });
      }

      doc.moveDown(1);
    }

    // ============================================================
    // COVER PAGE
    // ============================================================

    drawCover();

    // ============================================================
    // CONTENT PAGES
    // ============================================================

    if (sections.length > 0) {
      doc.addPage();

      drawPageHeader();

      doc.y = 72;

      // Contents label
      setFont(FONT.bold, 9, COLORS.primary);

      doc.text("CONTENTS", PAGE.marginLeft, doc.y);

      doc.moveDown(0.8);

      setFont(FONT.bold, 22, COLORS.text);

      doc.text(data.contentsTitle || "Report Contents", PAGE.marginLeft, doc.y);

      doc.moveDown(1);

      // Simple contents list
      sections.forEach((section, index) => {
        ensureSpace(35);

        const number = String(index + 1).padStart(2, "0");

        setFont(FONT.bold, 9, COLORS.primary);

        doc.text(number, PAGE.marginLeft, doc.y, {
          width: 30,
          lineBreak: false,
        });

        setFont(FONT.regular, 10.5, COLORS.body);

        doc.text(
          cleanText(section.heading || section.title || "Untitled Section"),
          PAGE.marginLeft + 35,
          doc.y,
          {
            width: 400,
            lineBreak: false,
          },
        );

        doc.moveDown(0.8);

        line(
          PAGE.marginLeft + 35,
          doc.y,
          PAGE.width - PAGE.marginRight,
          doc.y,
          COLORS.border,
          0.5,
        );

        doc.moveDown(0.5);
      });

      doc.addPage();

      drawPageHeader();

      doc.y = 72;

      // ========================================================
      // SECTIONS
      // ========================================================

      sections.forEach((section, index) => {
        drawSection(section, index);
      });
    }

    // ============================================================
    // FINAL NOTE
    // ============================================================

    if (data.endNote) {
      ensureSpace(100);

      doc.moveDown(1);

      roundedRect(
        PAGE.marginLeft,
        doc.y,
        PAGE.contentWidth,
        70,
        9,
        COLORS.background,
      );

      const noteY = doc.y;

      setFont(FONT.bold, 9, COLORS.primary);

      doc.text("NOTE", PAGE.marginLeft + 18, noteY + 15, {
        width: PAGE.contentWidth - 36,
        lineBreak: false,
      });

      setFont(FONT.regular, 9.5, COLORS.body);

      doc.text(cleanText(data.endNote), PAGE.marginLeft + 18, noteY + 32, {
        width: PAGE.contentWidth - 36,
        lineGap: 3,
      });

      doc.y = noteY + 90;
    }

    // ============================================================
    // END DOCUMENT
    // ============================================================

    doc.end();
  });
};
